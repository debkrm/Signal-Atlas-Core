#!/usr/bin/env python3
"""
Generates `reports/audit/INDEX.md` from the audit volume registry (Audit §78.15 (a)).

The index is a convenience, never a source of truth: it maps every top-level §N to its volume, its
line range and the finding ids the section names, and it is regenerated rather than hand-edited so a
transcribed number cannot drift from the volume it describes.

Usage:
    python scripts/generate_audit_index.py            # write reports/audit/INDEX.md
    python scripts/generate_audit_index.py --check    # exit 1 if the committed index is stale
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re
import sys
from typing import Dict, List, Optional

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
CONFIG_PATH = REPO_ROOT / "configs" / "audit_volumes.yaml"
INDEX_PATH = REPO_ROOT / "reports" / "audit" / "INDEX.md"

# Section headings are not uniform across the log: §1-§39 read "## 1. Title", §40-§53 read
# "## 40 — Title", §55-§78 read "## §75 — Title", and §54 carries no top-level heading at all (its
# first line is "### 54.1"). All of them are sections and all of them must be indexed, so a section
# starts at its first heading of any of those forms.
SECTION_HEADING = re.compile(r"^##\s*§?\s*(\d+)\s*(?:\.|\s+[—–-])\s*(.*)$")
SUBSECTION_HEADING = re.compile(r"^###\s*(\d+)\.\d+")
FINDING_ID = re.compile(r"\bN-\d+\b")


def load_volumes() -> List[dict]:
    with open(CONFIG_PATH, "r", encoding="utf-8") as f:
        data = yaml.safe_load(f) or {}
    volumes = data.get("volumes")
    if not isinstance(volumes, list) or not volumes:
        raise ValueError(f"audit_volumes.yaml has no 'volumes' list: {CONFIG_PATH}")
    return volumes


def scan_volume(path: Path) -> List[dict]:
    """Top-level sections of one volume, with line range and finding ids."""
    lines = path.read_text(encoding="utf-8").splitlines()
    starts: dict = {}
    weak_starts: dict = {}
    for number, line in enumerate(lines, start=1):
        match = SECTION_HEADING.match(line)
        if match:
            section = int(match.group(1))
            starts.setdefault(section, (number, match.group(2).strip()))
            continue
        weak = SUBSECTION_HEADING.match(line)
        if weak:
            weak_starts.setdefault(int(weak.group(1)), number)

    for section, line_no in weak_starts.items():
        starts.setdefault(section, (line_no, "(no top-level heading; first subsection)"))

    ordered = sorted(starts.items(), key=lambda kv: kv[1][0])
    sections: List[dict] = []
    for index, (section, (start, title)) in enumerate(ordered):
        end = ordered[index + 1][1][0] - 1 if index + 1 < len(ordered) else len(lines)
        body = lines[start - 1:end]
        findings = sorted(
            {finding for line in body for finding in FINDING_ID.findall(line)},
            key=lambda f: int(f.split("-")[1]),
        )
        sections.append({
            "section": section,
            "title": title or "(untitled)",
            "start": start,
            "end": end,
            "findings": findings,
        })
    return sections


def build_index() -> str:
    volumes = load_volumes()
    rows: List[str] = []
    header: List[str] = [
        "# Signal Atlas Core — Audit Index",
        "",
        "Generated by `scripts/generate_audit_index.py` from `configs/audit_volumes.yaml`. Do not edit by",
        "hand: the volumes are the source of truth and this file is a convenience over them.",
        "",
        "| Volume | Path | Sections | Lines | Frozen | SHA-256 |",
        "|---|---|---|---|---|---|",
    ]
    for volume in volumes:
        rel = str(volume["path"])
        path = REPO_ROOT / rel
        if not path.is_file():
            header.append(
                f"| `{Path(rel).name}` | `{rel}` | {volume.get('sections', '—')} | not created | "
                f"{'yes' if volume.get('frozen') else 'no'} | — |"
            )
            continue
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        line_count = len(path.read_text(encoding="utf-8").splitlines())
        frozen = "yes" if volume.get("frozen") else "no"
        header.append(
            f"| `{Path(rel).name}` | `{rel}` | {volume.get('sections', '—')} | {line_count} | "
            f"{frozen} | `{digest[:16]}…` |"
        )
        sections = scan_volume(path)
        declared = str(volume.get("sections", ""))
        declared_range = re.fullmatch(r"(\d+)-(\d+)", declared)
        if declared_range:
            expected = set(range(int(declared_range.group(1)), int(declared_range.group(2)) + 1))
            scoped = {section["section"] for section in sections}
            if scoped != expected:
                raise ValueError(
                    f"volume {rel} declares sections {declared} but the index found "
                    f"{sorted(scoped)} (missing {sorted(expected - scoped)}, "
                    f"unexpected {sorted(scoped - expected)})"
                )
        for section in sections:
            findings = ", ".join(section["findings"]) if section["findings"] else "—"
            rows.append(
                f"| §{section['section']} | {section['title']} | `{Path(rel).name}` | "
                f"{section['start']}–{section['end']} | {findings} |"
            )
    body = [
        "",
        "| Section | Title | Volume | Lines | Finding ids |",
        "|---|---|---|---|---|",
        *rows,
        "",
    ]
    return "\n".join(header + body) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate reports/audit/INDEX.md")
    parser.add_argument("--check", action="store_true", help="Fail if the committed index is stale")
    args = parser.parse_args()

    rendered = build_index()
    row_count = len([line for line in rendered.splitlines() if line.startswith("| §")])
    if args.check:
        if not INDEX_PATH.is_file():
            print(f"[FAIL] {INDEX_PATH.relative_to(REPO_ROOT).as_posix()} is missing")
            return 1
        if INDEX_PATH.read_text(encoding="utf-8") != rendered:
            print(
                f"[FAIL] {INDEX_PATH.relative_to(REPO_ROOT).as_posix()} is stale: regenerate it with "
                f"scripts/generate_audit_index.py"
            )
            return 1
        print(f"[PASS] Audit index matches the volumes ({row_count} section row(s)).")
        return 0

    INDEX_PATH.write_text(rendered, encoding="utf-8", newline="\n")
    print(
        f"Wrote {INDEX_PATH.relative_to(REPO_ROOT).as_posix()} "
        f"({row_count} section row(s))"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
